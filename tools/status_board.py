"""One table showing where every unit of the syllabus stands. Called from build.py.

Writes dist/editor/status-board.md and .html. Existing units are read from
content/units; units with no draft come from content/plan/units.yaml.
"""
from pathlib import Path

import yaml

import editor_pack

ROOT = Path(__file__).resolve().parent.parent
STAGES = ["Source held", "Harvested", "Cross-checked", "Drafted", "Audited", "Signed"]


def build(units, claims, sources):
    plan = yaml.safe_load((ROOT / "content/plan/units.yaml").read_text(encoding="utf-8")) or []
    rows, done_counts = [], [0] * 6
    for u in units:
        cs = editor_pack.used(u)
        waiting = sum(1 for c in cs if claims[c]["status"] == "ai-extracted")
        verified = sum(1 for c in cs if claims[c]["status"] == "expert-verified")
        st = [True, True, waiting == 0, True, bool(u.get("audited_by")), bool(u.get("signed_by"))]
        nxt = ("Release" if st[5] else "Editor sign-off" if st[2] and st[4] else
               "Audit by a non-Claude model" if st[2] else f"Cross-check {waiting} claim(s)" +
               ("" if st[4] else "; audit"))
        rows.append((u["id"], u["title"], u["tier"], st, f"{verified}/{len(cs)} claims verified", nxt))
    have = {u["id"] for u in units}
    for p in plan:
        if p["id"] in have:
            continue
        srcs = p.get("sources") or []
        held = any(s in sources and sources[s].get("held") for s in srcs)
        note = ", ".join(srcs) + (f" · needs {p['needs']}" if p.get("needs") else "")
        rows.append((p["id"], p["title"], p["tier"], [held, False, False, False, False, False], note,
                     f"{p['next']} ({p['task']})"))
    order = {"Detect": 0, "Foundation": 1, "Diagnose": 2, "Decide": 3}
    rows.sort(key=lambda r: (order.get(r[2], 9), r[0][0:2] if not r[0][1].isdigit() else r[0][0],
                             int("".join(ch for ch in r[0] if ch.isdigit()) or 0)))
    md = ["# Status board: every unit of the syllabus", "",
          "Generated by the build. A unit is released only when all six stages are done.",
          "Needs: C = cardiology co-editor, S = other specialist reviewer, K = Dr Kunda's own teaching.", "",
          "| Unit | Title | Tier | " + " | ".join(STAGES) + " | Detail | Next step |",
          "|---|---|---|" + "---|" * 6 + "---|---|"]
    for uid, title, tier, st, detail, nxt in rows:
        for i, s in enumerate(st):
            done_counts[i] += bool(s)
        md.append(f"| {uid} | {title} | {tier} | " + " | ".join("yes" if s else "-" for s in st) + f" | {detail} | {nxt} |")
    md += ["", f"**{len(rows)} units.** " + "; ".join(f"{STAGES[i]}: {done_counts[i]}" for i in range(6)) + ".", ""]
    out = ROOT / "dist" / "editor"
    out.mkdir(parents=True, exist_ok=True)
    (out / "status-board.md").write_text("\n".join(md), encoding="utf-8")
    (out / "status-board.html").write_text(
        editor_pack.to_html(md).replace("<title>Editor's review pack</title>", "<title>Status board</title>"),
        encoding="utf-8")
    print(f"built status board: {len(rows)} units; drafted {done_counts[3]}, signed {done_counts[5]} -> dist/editor/")
